#!/usr/bin/env python3
"""Independent specification for wrap_sources2.pl. Writes 200 io pairs to
tests/wrap_sources2_io.pl.

io(N, Folder, InName, InText, OutName, OutText):
  the file Books/Folder/InName holding InText should, after wrap_sources,
  be the file Books/Folder/OutName holding OutText (and InName is gone if
  the names differ).

Rule: a name starting with "dot-" and ending in ".txt" or ".pl" becomes the
name without "dot-", holding
  ["Green, L., 2026, <i>Title</i>, Lucian Academy Press, Melbourne.","Green, 2026",1,"Text"]
with every " in Text written as \\". Any other file is left as it is.
"""
import random

random.seed(2026)
WORDS = ["Saint", "New Sales", "Simulation", "Music", "Miracles", "Time Travel",
         "Medicine", "Pedagogy", "Immortality", "Popology"]
SENTENCES = ["1. I wrote the algorithm.", "2. She said \"yes\" to the plan.",
             "3. The bot \"marked\" the essay, and then it \"slept\".",
             "4. A list [1,2,3] and a term f(x).", "5. Plain line with commas, colons: and dashes - here.",
             "6. Lines\nacross\nthree lines.", "7. Back\\slash stays.", ""]
FOLDERS = ["Saint", "SALES", "SIMULATION", "MUSIC"]
KINDS = ["dot_txt", "dot_pl", "plain_txt", "dot1_txt", "dot_md"]


def pl_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def expected(name, text):
    if name.startswith("dot-") and (name.endswith(".txt") or name.endswith(".pl")):
        base = name[4:]
        title = base[:-4] if base.endswith(".txt") else base[:-3]
        body = text.replace('"', '\\"')
        return base, ('["Green, L., 2026, <i>' + title +
                      '</i>, Lucian Academy Press, Melbourne.","Green, 2026",1,"' + body + '"]')
    return name, text


def main():
    lines = [":- module(wrap_sources2_io, [io/6]).",
             "% Generated by tests/make_wrap_sources2_io.py. Do not edit by hand.", ""]
    for n in range(1, 201):
        kind = KINDS[(n - 1) % len(KINDS)]
        folder = FOLDERS[(n - 1) % len(FOLDERS)]
        title = f"{random.choice(WORDS)} {n}"
        name = {"dot_txt": f"dot-{title}.txt", "dot_pl": f"dot-{title}.pl",
                "plain_txt": f"{title}.txt", "dot1_txt": f"dot1-{title}.txt",
                "dot_md": f"dot-{title}.md"}[kind]
        text = "\n".join(random.sample(SENTENCES, random.randint(1, 3)))
        out_name, out_text = expected(name, text)
        lines.append(f"io({n}, {pl_str(folder)}, {pl_str(name)}, {pl_str(text)}, "
                     f"{pl_str(out_name)}, {pl_str(out_text)}).")
    with open("tests/wrap_sources2_io.pl", "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
